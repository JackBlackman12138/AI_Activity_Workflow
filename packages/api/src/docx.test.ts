test('Word 解析保留图文与表格，清理脚本链接，拒绝损坏和超大压缩包', async () => {
  const buffer = docxFixture();
  const imported = await importDocx(buffer, '原稿.docx');
  assert.match(imported.markdown, /玩家收集材料/);
  assert.match(imported.markdown, /\| 节点 \| 奖励 \|/);
  assert.match(imported.markdown, /attachment:/);
  assert.equal(imported.document.images.length, 1);
  assert.equal(imported.document.images[0]?.mimeType, 'image/png');
  assert.equal(imported.document.originalBase64, buffer.toString('base64'));
  assert.ok(!imported.markdown.includes('javascript:'));
  assert.throws(() => checkDocxArchive(Buffer.from('fake word')), /DOCX/);
  const huge = Buffer.from(buffer); const central = huge.indexOf(Buffer.from('504b0102', 'hex')); huge.writeUInt32LE(100_000_000, central + 24);
  assert.throws(() => checkDocxArchive(huge), /过大/);
});

